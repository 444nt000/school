int	ft_atoi(const char *str)
{
	int		nb;
	short	sign;

	sign = -1;
	nb = 0;
	while (*str == ' ' || (*str >= 9 && *str <= 13))
		str++;
	if (*str == '+')
		str++;
	else if (*str == '-')
	{
		sign = 1;
		str++;
	}
	while (*str >= '0' && *str <= '9')
		nb = nb * 10 - (*str++ - '0');
	return (nb * sign);
}
